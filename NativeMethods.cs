        public static bool PromoteToTopMost(IntPtr hWnd, out int win32Error)
        {
            win32Error = 0;
            if (hWnd == IntPtr.Zero || !IsWindow(hWnd))
            {
                win32Error = 1400;
                return false;
            }
            bool success = SetWindowPos(hWnd, HWND_TOPMOST, 0, 0, 0, 0,
                SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE | SWP_SHOWWINDOW);
            if (!success)
            {
                win32Error = Marshal.GetLastWin32Error();
            }
            return success;
        }

        public static bool HasTopMostStyle(IntPtr hWnd)
        {
            if (hWnd == IntPtr.Zero || !IsWindow(hWnd)) return false;
            long exStyle = (long)GetWindowLongPtr(hWnd, GWL_EXSTYLE);
            return (exStyle & WS_EX_TOPMOST) != 0;
        }

        public static bool IsWindowAbove(IntPtr hWndUpper, IntPtr hWndLower)
        {
            if (hWndUpper == IntPtr.Zero || hWndLower == IntPtr.Zero || hWndUpper == hWndLower)
                return false;

            IntPtr current = GetWindow(hWndUpper, GW_HWNDNEXT);
            while (current != IntPtr.Zero)
            {
                if (current == hWndLower) return true;
                current = GetWindow(current, GW_HWNDNEXT);
            }
            return false;
        }

